
package com.smartbasket.backend.customer.dto;

import jakarta.validation.constraints.DecimalMin;
import jakarta.validation.constraints.Max;
import jakarta.validation.constraints.Min;
import jakarta.validation.constraints.NotNull;

import java.math.BigDecimal;

public class BudgetRequest {

    @NotNull(message = "Customer ID is required")
    @Min(value = 1, message = "Invalid customer ID")
    private Long customerId;

    @NotNull(message = "Shop ID is required")
    @Min(value = 1, message = "Invalid shop ID")
    private Long shopId;

    @NotNull(message = "Monthly budget is required")
    @DecimalMin(
            value = "0.0",
            inclusive = false,
            message = "Monthly budget must be greater than zero"
    )
    private BigDecimal monthlyBudget;

    @NotNull(message = "Month is required")
    @Min(value = 1, message = "Month must be between 1 and 12")
    @Max(value = 12, message = "Month must be between 1 and 12")
    private Integer month;

    @NotNull(message = "Year is required")
    @Min(value = 2000, message = "Invalid year")
    @Max(value = 2100, message = "Invalid year")
    private Integer year;

    public BudgetRequest() {
    }

    public Long getCustomerId() {
        return customerId;
    }

    public void setCustomerId(Long customerId) {
        this.customerId = customerId;
    }

    public Long getShopId() {
        return shopId;
    }

    public void setShopId(Long shopId) {
        this.shopId = shopId;
    }

    public BigDecimal getMonthlyBudget() {
        return monthlyBudget;
    }

    public void setMonthlyBudget(BigDecimal monthlyBudget) {
        this.monthlyBudget = monthlyBudget;
    }

    public Integer getMonth() {
        return month;
    }

    public void setMonth(Integer month) {
        this.month = month;
    }

    public Integer getYear() {
        return year;
    }

    public void setYear(Integer year) {
        this.year = year;
    }
}
